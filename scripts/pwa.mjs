// Post-processes `expo export -p web` output in dist/ into an installable,
// offline-capable PWA that works on GitHub Pages under a sub-path.
//   - dist/manifest.webmanifest
//   - PWA <head> tags + service-worker registration in index.html
//   - dist/sw.js that precaches every built file
//   - 404.html (SPA deep links on GitHub Pages) and .nojekyll
import { createHash } from 'node:crypto';
import { copyFileSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';
const BASE = (process.env.BASE_URL ?? '').replace(/\/$/, '');
const THEME = '#0B0C0A';

const manifest = {
  name: 'Lexicard — words, idioms & phrases',
  short_name: 'Lexicard',
  description: 'Swipe to learn words, idioms and phrases. Tap for how to use them and where they come from.',
  id: `${BASE}/`,
  start_url: `${BASE}/`,
  scope: `${BASE}/`,
  display: 'standalone',
  orientation: 'portrait',
  background_color: THEME,
  theme_color: THEME,
  categories: ['education', 'productivity'],
  icons: [
    { src: `${BASE}/icons/icon-192.png`, sizes: '192x192', type: 'image/png' },
    { src: `${BASE}/icons/icon-512.png`, sizes: '512x512', type: 'image/png' },
    { src: `${BASE}/icons/maskable-512.png`, sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};
writeFileSync(join(DIST, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));

const head = `
    <link rel="manifest" href="${BASE}/manifest.webmanifest">
    <meta name="theme-color" content="${THEME}">
    <meta name="description" content="${manifest.description}">
    <meta name="mobile-web-app-capable" content="yes">
    <meta name="apple-mobile-web-app-capable" content="yes">
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
    <meta name="apple-mobile-web-app-title" content="Lexicard">
    <link rel="apple-touch-icon" href="${BASE}/icons/apple-touch-icon.png">
    <style>html,body{background:${THEME}}</style>
    <script>
      if ('serviceWorker' in navigator) {
        window.addEventListener('load', function () {
          navigator.serviceWorker.register('${BASE}/sw.js', { scope: '${BASE}/' }).catch(function () {});
        });
      }
    </script>
`;
const indexPath = join(DIST, 'index.html');
let html = readFileSync(indexPath, 'utf8');
if (!html.includes('rel="manifest"')) html = html.replace('</head>', `${head}</head>`);
html = html.replace(/<title>[^<]*<\/title>/, '<title>Lexicard</title>');
html = html.replace(/<meta name="viewport"[^>]*>/, '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">');
writeFileSync(indexPath, html);
copyFileSync(indexPath, join(DIST, '404.html'));
writeFileSync(join(DIST, '.nojekyll'), '');

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}
const files = walk(DIST)
  .map((p) => relative(DIST, p).split(sep).join('/'))
  .filter((f) => !['sw.js', '404.html', '.nojekyll'].includes(f) && !f.endsWith('.map'));
// Audio is large; it is cached on first play (or via "Download audio" in the Library), not at install.
const precacheFiles = files.filter((f) => !f.endsWith('.mp3'));
const hash = createHash('sha1');
for (const f of precacheFiles.sort()) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);
const precache = [`${BASE}/`, ...precacheFiles.map((f) => `${BASE}/${f}`)];

const sw = `// Generated by scripts/pwa.mjs — do not edit.
const VERSION = 'lexicard-${version}';
const BASE = '${BASE}';
const PRECACHE = ${JSON.stringify(precache)};
const AUDIO_CACHE = 'lexicard-audio';

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(VERSION).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('lexicard-') && k !== VERSION && k !== AUDIO_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;

  // Pages: network first so deploys show up, cached app shell when offline.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(() => caches.match(BASE + '/index.html').then((r) => r || caches.match(BASE + '/'))),
    );
    return;
  }

  // Audio: always cache the full file, then answer Range requests (Safari needs them) from it.
  if (new URL(req.url).pathname.endsWith('.mp3')) {
    event.respondWith(
      caches.open(AUDIO_CACHE).then(async (cache) => {
        let full = await cache.match(req.url);
        if (!full) {
          const res = await fetch(req.url);
          if (res.status !== 200) return res;
          await cache.put(req.url, res.clone());
          full = res;
        }
        return rangeResponse(req, full);
      }),
    );
    return;
  }

  // Assets are content-hashed: cache first, fill the cache on miss.
  event.respondWith(
    caches.match(req).then((hit) =>
      hit ||
      fetch(req).then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(VERSION).then((c) => c.put(req, copy));
        }
        return res;
      }),
    ),
  );
});

async function rangeResponse(req, full) {
  const range = req.headers.get('range');
  if (!range) return full;
  const buf = await full.clone().arrayBuffer();
  const m = /bytes=(\\d*)-(\\d*)/.exec(range);
  if (!m) return full;
  const size = buf.byteLength;
  let start = m[1] ? Number(m[1]) : size - Number(m[2]);
  let end = m[1] && m[2] ? Number(m[2]) : size - 1;
  end = Math.min(end, size - 1);
  const body = buf.slice(start, end + 1);
  return new Response(body, {
    status: 206,
    headers: {
      'Content-Type': full.headers.get('Content-Type') || 'audio/mpeg',
      'Content-Range': 'bytes ' + start + '-' + end + '/' + size,
      'Content-Length': String(body.byteLength),
      'Accept-Ranges': 'bytes',
    },
  });
}
`;
writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`PWA ready: ${precache.length} files precached, version ${version}, base "${BASE || '/'}"`);
